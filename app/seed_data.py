def seed():
    db = SessionLocal()
    try:
        if db.query(QuickReply).count() == 0:
            for cat, title, kw, sc, content in SEED_REPLIES:
                db.add(QuickReply(category=cat, title=title, keywords=kw,
                                  shortcut=sc or "", content=content))
        if db.query(DocTemplate).count() == 0:
            for name, cat, content in SEED_DOC_TEMPLATES:
                db.add(DocTemplate(name=name, category=cat, content=content))
        db.commit()
        return {"replies": len(SEED_REPLIES), "doctpl": len(SEED_DOC_TEMPLATES)}
    finally:
        db.close()


